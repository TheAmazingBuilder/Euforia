/** Builder type shared by the module-scope label builders (see components). */
export type SessionDict = Dictionary["session"];

/** Market-bias enum → dict label (composition/case stays in components). */
export function biasLabel(S: SessionDict, bias: "BULLISH" | "BEARISH" | "NEUTRAL"): string {
  return bias === "BULLISH" ? S.bias.bullish : bias === "BEARISH" ? S.bias.bearish : S.bias.neutral;
}

/** KeyLevelKind enum → dict label (fallback keeps the legacy de-spaced kind). */
const LEVEL_KIND_KEYS = {
  SUPPORT: "support",
  RESISTANCE: "resistance",
  PREV_DAY_HIGH: "prevDayHigh",
  PREV_DAY_LOW: "prevDayLow",
  SESSION_OPEN: "sessionOpen",
  WEEKLY_HIGH: "weeklyHigh",
  WEEKLY_LOW: "weeklyLow",
  ASIAN_HIGH: "asianHigh",
  ASIAN_LOW: "asianLow",
  CUSTOM: "custom",
} as const;

export function levelKindLabel(S: SessionDict, kind: string): string {
  const key = LEVEL_KIND_KEYS[kind as keyof typeof LEVEL_KIND_KEYS];
  return key !== undefined ? S.levelKinds[key] : kind.replace(/_/g, " ");
}

